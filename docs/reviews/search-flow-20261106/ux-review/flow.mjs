import { chromium } from '/home/lsh/.cache/hairline-look/node_modules/playwright-core/index.mjs';
const browser=await chromium.launch({executablePath:'/home/lsh/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const root='/home/lsh/ONE/.oil-ui/search-flow-20261106/ux-review/';
await page.goto('http://127.0.0.1:5570/one-g/products/',{waitUntil:'networkidle'});
console.log('BUTTONS',await page.getByRole('button').evaluateAll(es=>es.map(e=>({text:e.innerText,label:e.getAttribute('aria-label')}))));
await page.getByRole('button',{name:'搜索',exact:true}).first().click();
console.log('SEARCH OPEN',await page.locator('body').innerText());
console.log('INPUTS',await page.getByRole('searchbox').evaluateAll(es=>es.map(e=>({placeholder:e.getAttribute('placeholder')}))));
await page.screenshot({path:root+'02-search-open.png'});
await page.getByRole('searchbox').fill('G1');
await page.getByRole('searchbox').press('Enter');
await page.waitForTimeout(500);
console.log('RESULTS',await page.locator('body').innerText());
await page.screenshot({path:root+'03-search-result.png'});
console.log('LINKS',await page.getByRole('link').evaluateAll(es=>es.filter(e=>e.innerText.includes('G1')).map(e=>({text:e.innerText,href:e.getAttribute('href')}))));
await page.getByRole('link',{name:'ONE-G G1 商品',exact:true}).click();
await page.waitForTimeout(500);
console.log('DETAIL URL',page.url());
console.log('DETAIL',await page.locator('body').innerText());
await page.screenshot({path:root+'04-g1-detail.png',fullPage:true});
await browser.close();
